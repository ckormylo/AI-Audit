// Turns the latest real runs in data/attempt_log.jsonl into data/replay.js, so the public copy (GitHub Pages, no Ollama)
// and any machine without the models show the real transcript set, sample grid and name-swap replies instead of the written fallback.
//   node scripts/make_replay.mjs            (run from the deck folder after Generate and the two live slides have been run)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const logFile = path.join(root, "data", "attempt_log.jsonl");
if (!fs.existsSync(logFile)) { console.error("no data/attempt_log.jsonl yet; press Generate on the transcript slide first"); process.exit(1); }
const runs = {};
for (const line of fs.readFileSync(logFile, "utf8").split("\n")) {
  if (!line.trim()) continue;
  let j; try { j = JSON.parse(line); } catch (e) { continue; }
  if (!j.kind || !j.run) continue;
  (runs[j.kind + ":" + j.run] = runs[j.kind + ":" + j.run] || []).push(j);
}
const latest = (kind) => { const keys = Object.keys(runs).filter((k) => k.startsWith(kind + ":")).sort(); return keys.length ? runs[keys[keys.length - 1]] : []; };
const transcripts = latest("transcript"), grid = latest("grid"), nameSwap = latest("nameswap");
if (transcripts.length < 12) { console.error("the latest transcript run has only " + transcripts.length + " rows; not writing"); process.exit(1); }
const first = transcripts[0];
const out = {
  label: "real run · " + first.run + " · " + (first.config ? first.config.model + " · " + first.config.promptVersion : ""),
  illustrative: false,
  config: first.config || {},
  transcripts: transcripts.map((r) => ({ id: r.id, question_id: r.question_id, sample: r.sample, retrieved_doc: r.retrieved_doc, source_doc: r.source_doc, reply: r.reply, judge: r.judge })),
  sampleGrid: grid.map((r) => ({ reply: r.reply, judge: r.judge })),
  nameSwap: nameSwap.map((r) => ({ group: r.group, name: r.name, sample: r.sample, reply: r.reply })),
};
const prev = path.join(root, "data", "replay.js");
if (fs.existsSync(prev) && /illustrative":\s*true/.test(fs.readFileSync(prev, "utf8").slice(0, 400))) fs.copyFileSync(prev, path.join(root, "data", "replay_written_fallback.js"));
fs.writeFileSync(prev, "// Real runs from data/attempt_log.jsonl (generated by scripts/make_replay.mjs). The written fallback is kept in replay_written_fallback.js.\nwindow.L15_REPLAY = " + JSON.stringify(out, null, 1) + ";\n");
console.log("wrote data/replay.js:", transcripts.length, "transcripts,", grid.length, "grid replies,", nameSwap.length, "name-swap replies (" + first.run + ")");
