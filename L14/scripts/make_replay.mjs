// Turns data/attempt_log.jsonl (written by start-deck during rehearsal) into data/replay.js for replay mode.
//   node scripts/make_replay.mjs            -> keeps the last record of each attempt id, live attempts only
//   node scripts/make_replay.mjs --all      -> includes attempts without a class verdict
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "data", "attempt_log.jsonl");
if (!fs.existsSync(src)) { console.error("No data/attempt_log.jsonl yet. Run a rehearsal with start-deck first."); process.exit(1); }
const byId = new Map();
for (const line of fs.readFileSync(src, "utf8").split("\n")) {
  if (!line.trim()) continue;
  try { const r = JSON.parse(line); byId.set(r.id, r); } catch (e) {}
}
const all = process.argv.includes("--all");
const items = [...byId.values()]
  .filter((r) => !r.replay && r.turns && r.turns.length && (all || r.classVerdict))
  .map((r) => ({ technique: r.technique, label: r.label || "", config: r.config, classVerdict: r.classVerdict,
    turns: r.turns.map((t) => ({ user: t.user, retrieved: t.retrieved, bot: t.bot, judge: t.judge })) }));
const out = "// Rehearsal transcripts for replay mode. Generated by scripts/make_replay.mjs from data/attempt_log.jsonl on " + new Date().toISOString().slice(0, 10) + ". Do not edit by hand.\nwindow.REPLAY = " + JSON.stringify({ items }, null, 1) + ";\n";
fs.writeFileSync(path.join(root, "data", "replay.js"), out);
console.log(`replay.js written: ${items.length} attempts (${[...new Set(items.map((i) => i.technique))].join(", ")})`);
